import { expect, test } from "@playwright/test";

const entry = "10000000-0000-0000-0000-000000000001.20000000-0000-0000-0000-000000000001";

test("creates, assigns, renames, filters and removes personal tags", async ({ page, request }) => {
  expect((await request.post("http://127.0.0.1:8106/reset")).ok()).toBe(true);
  await page.goto("/acesso");
  await page.getByLabel("E-mail").fill("browser-owner@category-e2e.example.test");
  await page.getByLabel("Senha", { exact: true }).fill("balsave-category-browser-tests-only-password");
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto("/lancamentos");
  const ledger = page.getByRole("region", { name: "Histórico de lançamentos" });
  await expect(ledger.getByRole("columnheader", { name: "Classificações", exact: true })).toHaveCount(1);
  await expect(ledger.getByRole("columnheader", { name: "Etiquetas", exact: true })).toHaveCount(1);
  await ledger.getByRole("button", { name: "Adicionar etiquetas a Loja de equipamentos" }).click();
  const editor = page.getByRole("dialog", { name: "Etiquetas", exact: true });
  await expect(editor).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  for (const name of ["Trabalho", "Viagem"]) {
    await editor.getByRole("searchbox").fill(name);
    await editor.getByRole("button", { name: `＋ Criar “${name}”` }).click();
    await expect(editor.getByRole("button", { name: `Remover etiqueta ${name}`, exact: true })).toBeVisible();
  }
  await page.keyboard.press("Escape");
  await expect(editor).not.toBeVisible();
  const editTags = ledger.getByRole("button", { name: /^Editar etiquetas de Loja de equipamentos/ });
  await expect(editTags).toBeFocused();
  const work = editTags.getByText("Trabalho", { exact: true });
  await expect(work).toBeVisible();
  const workColor = await work.getAttribute("data-color");
  await page.reload();
  await editTags.click();
  await expect(editor.getByRole("button", { name: "Trabalho", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(editor.getByRole("button", { name: "Viagem", exact: true })).toHaveAttribute("aria-pressed", "true");
  await editor.getByRole("link", { name: "Gerenciar etiquetas" }).click();
  await expect(page).toHaveURL(/\/classificacoes\?aba=etiquetas$/);
  const listedWork = page.getByRole("button", { name: /Trabalho.*1 lançamento/ });
  await listedWork.click();
  const rename = page.getByRole("dialog", { name: "Editar etiqueta", exact: true });
  await rename.getByLabel("Nome da etiqueta").fill("Escritório");
  await rename.getByRole("button", { name: "Salvar nome", exact: true }).click();
  await expect(page.getByRole("button", { name: /Escritório.*1 lançamento/ })).toBeVisible();
  await page.getByRole("button", { name: "Nova etiqueta", exact: true }).click();
  const creator = page.getByRole("dialog", { name: "Nova etiqueta", exact: true });
  await creator.getByLabel("Nome da etiqueta").fill("Outra etiqueta");
  await creator.getByRole("button", { name: "Criar etiqueta", exact: true }).click();
  await expect(page.getByRole("button", { name: /Outra etiqueta.*0 lançamentos/ })).toBeVisible();
  await page.goto("/lancamentos");
  expect(await editTags.getByText("Escritório", { exact: true }).getAttribute("data-color")).toBe(workColor);

  const tagFilter = page.getByRole("combobox", { name: "Filtrar por etiquetas" });
  const tagOptions = page.getByRole("listbox", { name: "Etiquetas" });
  await tagFilter.click();
  const purchase = ledger.getByRole("link", { name: "Loja de equipamentos", exact: true });
  await tagOptions.getByRole("option", { name: "Outra etiqueta" }).click();
  await expect(tagOptions.getByRole("option", { name: "Outra etiqueta" })).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("Escape");
  await expect(tagFilter).toBeFocused();
  await expect(purchase).toHaveCount(0);
  await tagFilter.click();
  await tagOptions.getByRole("option", { name: "Limpar etiquetas" }).click();
  await page.keyboard.press("Escape");
  await expect(page).not.toHaveURL(/etiquetas=/);
  await expect(purchase).toHaveCount(1);
  await tagFilter.click();
  for (const name of ["Escritório", "Viagem"]) {
    const filter = tagOptions.getByRole("option", { name, exact: true });
    await filter.click();
    await expect(filter).toHaveAttribute("aria-selected", "true");
  }
  await page.keyboard.press("Escape");
  await expect(tagFilter).toHaveText("Etiquetas (2)");
  await expect(page).toHaveURL(/etiquetas=/);
  await expect(purchase).toHaveCount(1);
  await expect(ledger.locator("dl").getByText(/^R\$\s125,00$/)).toBeVisible();
  await page.getByLabel("Período").selectOption({ label: "Personalizado" });
  await page.getByLabel("Data final").fill("2026-11-14");
  await expect(purchase).toHaveCount(0);
  await expect(ledger.locator("dl").getByText(/^R\$\s0,00$/)).toHaveCount(3);
  await page.getByLabel("Data final").fill("2026-11-15");
  await expect(purchase).toHaveCount(1);

  await page.getByRole("link", { name: "Voltar ao painel" }).click();
  await expect(tagFilter).toHaveText("Etiquetas (2)");
  await expect(page.getByRole("region", { name: "Gastos por categoria" }).getByText(/^R\$\s125,00$/)).toBeVisible();
  await page.getByRole("link", { name: "Ver gastos", exact: true }).click();
  await expect(page).toHaveURL(/etiquetas=/);
  await expect(tagFilter).toHaveText("Etiquetas (2)");
  await expect(page.getByRole("region", { name: "Compras no período" }).locator("dl").getByText(/^R\$\s125,00$/)).toBeVisible();

  await page.goto("/lancamentos");
  await editTags.click();
  await editor.getByRole("button", { name: "Remover etiqueta Viagem", exact: true }).click();
  await expect(editor.getByRole("button", { name: "Viagem", exact: true })).toHaveAttribute("aria-pressed", "false");
  await editor.getByRole("button", { name: "Fechar seletor", exact: true }).click();
  await expect(editTags.getByText("Escritório", { exact: true })).toBeVisible();
  await expect(editTags.getByText("Viagem", { exact: true })).toHaveCount(0);
  await page.goto(`/lancamentos?lancamento=${entry}`);
  const detailEditor = page.getByRole("region", { name: "Etiquetas", exact: true });
  await expect(detailEditor.getByRole("checkbox", { name: "Escritório" })).toBeChecked();
  await expect(detailEditor.getByRole("checkbox", { name: "Viagem" })).not.toBeChecked();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);

  await page.goto("/classificacoes?aba=etiquetas");
  const office = page.getByRole("button", { name: /Escritório.*1 lançamento/ });
  await office.click();
  await rename.getByRole("button", { name: "Excluir etiqueta", exact: true }).click();
  const confirmation = page.getByRole("dialog", { name: "Excluir etiqueta", exact: true });
  await expect(confirmation.getByText("Uso atual: 1 lançamento.")).toBeVisible();
  await confirmation.getByRole("button", { name: "Voltar", exact: true }).click();
  await expect(rename.getByLabel("Nome da etiqueta")).toHaveValue("Escritório");
  await rename.getByRole("button", { name: "Excluir etiqueta", exact: true }).click();
  await confirmation.getByRole("button", { name: "Confirmar exclusão" }).click();
  await expect(confirmation).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Escritório/ })).toHaveCount(0);
  await expect(page.getByRole("button", { name: /Viagem.*0 lançamentos/ })).toBeVisible();
  await page.goto(`/lancamentos?lancamento=${entry}`);
  await expect(detailEditor.getByRole("checkbox", { name: "Escritório" })).toHaveCount(0);
});
